function plural(n: number, one: string, other: string): string {
  return n === 1 ? one : other;
}

/** «12 days» or «5 weeks». */
function streakIn(count: number, unit: StreakUnit): string {
  return `${count} ${unit === "days" ? plural(count, "day", "days") : plural(count, "week", "weeks")}`;
}

